test("reader keeps a readable measure and secondary tools at desktop sizes", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("article").first().click();
  const reader = page.locator(".drawer.reader");
  const tools = reader.locator(".reader-tools");
  await expect(reader).toBeVisible();
  await expect(reader.getByRole("button", { name: "生成本篇摘要" })).toBeVisible();
  await tools.locator("summary").click();
  await expect(reader.getByRole("button", { name: "生成本篇摘要" })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(tools).not.toHaveAttribute("open", "");
  await expect(reader).toBeVisible();
  await reader.getByRole("button", { name: "翻译", exact: true }).click();
  await expect(reader.locator(".reader-view-rail")).toBeVisible();
  await expect(tools).not.toHaveAttribute("open", "");

  for (const width of [1600, 880]) {
    await page.setViewportSize({ width, height: width === 880 ? 560 : 900 });
    for (const theme of ["light", "dark"]) {
      await page.evaluate(t => { document.documentElement.dataset.theme = t; }, theme);
      const column = await reader.locator(".reader-column").boundingBox();
      const rail = await reader.locator(".reader-view-rail").boundingBox();
      expect(column!.width).toBeLessThanOrEqual(760);
      expect(column!.width).toBeGreaterThan(500);
      expect(column!.x + column!.width).toBeLessThan(rail!.x);
      expect(await reader.evaluate(e => e.scrollWidth <= e.clientWidth)).toBe(true);
      await shot(page, `../../test-results/reader-polish-20260917/reader-${width}-${theme}.png`);
    }
    await tools.locator("summary").click();
    const panel = await tools.locator(".reader-tools-panel").boundingBox();
    expect(panel!.x).toBeGreaterThanOrEqual(0);
    expect(panel!.x + panel!.width).toBeLessThanOrEqual(width);
    await expect(reader.getByRole("button", { name: "生成本篇摘要" })).toBeVisible();
    await reader.locator(".reader-title").click();
    await expect(tools).not.toHaveAttribute("open", "");
    await reader.locator(".drawer-body").evaluate(el => { el.scrollTop = el.scrollHeight; });
    await expect(reader.getByRole("radio", { name: "译文", exact: true })).toBeVisible();
    await reader.locator(".drawer-body").evaluate(el => { el.scrollTop = 0; });
  }
  await reader.getByRole("button", { name: "返回", exact: true }).click();
  await expect(reader).toHaveCount(0);
});

test("full-window reader has timed tips, a scroll title and container-sized opening", async ({ page }) => {
  const { installMockHost } = await import("./mockHost");
  const { readerReturnFixture } = await import("../src/test/fixtures/reader");
  const fixture = readerReturnFixture(6);
  await installMockHost(page, fixture);
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.goto("/");
  await page.getByRole("article").first().click();
  const stage = page.locator(".reader-stage");
  const reader = page.locator(".drawer.reader");
  const body = reader.locator(".drawer-body");
  await expect(reader.locator(".reader-title")).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  expect(await reader.boundingBox()).toEqual({ x: 0, y: 0, width: 1280, height: 800 });
  await expect(stage.locator(".overlay-dismiss")).toHaveCount(0);
  expect(await page.evaluate(() => !!document.elementFromPoint(100, 300)?.closest(".reader-stage"))).toBe(true);
  await expect(reader).toHaveCSS("border-radius", "0px");
  await expect(reader.locator(".reader-head")).toHaveCSS("height", "48px");
  await expect(reader.locator(".reader-position")).toHaveText("1 / 6");
  await page.keyboard.press("j");
  await expect(reader.locator(".reader-position")).toHaveText("2 / 6");
  await page.mouse.move(1279, 799);
  const previous = reader.getByRole("button", { name: "上一篇", exact: true });
  await page.clock.install();
  await page.clock.pauseAt(new Date());
  await previous.dispatchEvent("mouseover");
  await page.clock.runFor(399);
  expect(await reader.getByRole("tooltip", { name: "上一篇 · K", exact: true }).count()).toBe(0);
  await page.clock.runFor(1);
  await expect(reader.getByRole("tooltip", { name: "上一篇 · K", exact: true })).toBeVisible();
  await previous.dispatchEvent("mouseout");
  await previous.focus();
  await expect(reader.getByRole("tooltip", { name: "上一篇 · K", exact: true })).toBeVisible();
  await previous.evaluate(el => el.blur());
  await page.clock.resume();
  await body.evaluate(el => { el.scrollTop = 121; });
  await expect(reader.locator(".reader-scroll-title")).toBeVisible();
  await expect(reader.locator(".reader-scroll-title")).toContainText(fixture.readers[2].title);
  await reader.locator(".reader-scroll-title").click();
  await expect.poll(() => body.evaluate(el => el.scrollTop)).toBe(0);
  await expect(reader.locator(".reader-scroll-title")).toBeHidden();
  await page.keyboard.press("k");
  await page.mouse.move(1279, 799);
  await page.keyboard.press("l");
  const drawer = page.locator(".reader-article-drawer");
  await expect(drawer).toBeVisible();
  await drawer.getByRole("button", { name: "钉住", exact: true }).click();
  await expect(stage).toHaveAttribute("data-drawer-pinned", "true");
  expect((await reader.boundingBox())!.x).toBe(340);
  await page.mouse.move(1279, 799);
  await expect(reader.locator(".reader-column")).toHaveCSS("width", "640px");
  await expect(reader.locator(".reader-title")).toHaveCSS("font-size", "31px");
  await drawer.getByRole("button", { name: "取消钉住", exact: true }).click();
  await page.keyboard.press("l");
  await expect(reader.locator(".reader-column")).toHaveCSS("width", "720px");
  await expect(reader.locator(".reader-title")).toHaveCSS("font-size", "34px");
  await body.evaluate(el => { el.scrollTop = 200; });
  await page.setViewportSize({ width: 700, height: 800 });
  await expect(body).toHaveCSS("padding-left", "36px");
});

test("article typography, code copying and the compact language rail preserve interaction", async ({ page, context }) => {
  const { installMockHost } = await import("./mockHost");
  const { readerMenuFixtures, TWO_ARTICLE_PAGE } = await import("../src/test/fixtures/reader");
  const fixture = readerMenuFixtures().translated;
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await installMockHost(page, { focus: TWO_ARTICLE_PAGE, reader: { ...fixture, id: 1 } });
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.goto("/");
  await page.getByRole("article").first().click();
  const reader = page.locator(".drawer.reader"), body = reader.locator(".drawer-body");
  const code = reader.locator("pre").first();
  await code.hover();
  await code.getByRole("button", { name: "复制代码" }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe("open 09:00\nclose 21:00");
  await body.evaluate(el => { el.scrollTop = 0; });
  const rail = reader.getByRole("radiogroup", { name: "译文视图" });
  const bilingual = rail.getByRole("radio", { name: "双语", exact: true });
  await page.mouse.move(1279, 799);
  // 假时钟从给定起点走真实时间；暂停点留 1 秒余量，免得落在已走过的时刻（Cannot fast-forward to the past）。
  await page.clock.install({ time: Date.now() });
  await page.clock.pauseAt(Date.now() + 1000);
  await bilingual.dispatchEvent("mouseover");
  await page.clock.runFor(299);
  expect(await rail.getByRole("tooltip").count()).toBe(0);
  await page.clock.runFor(1);
  await expect(rail.getByRole("tooltip")).toHaveText("双语 · V");
  await bilingual.dispatchEvent("mouseout");
  await bilingual.click();
  await page.clock.resume();
  await expect(bilingual).toBeChecked();
  await expect(reader.locator(".reader-title")).toHaveText("Opening Day");
  await expect(reader.locator(".reader-original-title")).toHaveText("开馆日");
  await expect(bilingual).toHaveCSS("width", "28px");
  await page.keyboard.press("v");
  await expect(rail.getByRole("radio", { name: "译文" })).toBeChecked();
  await expect(reader.locator(".block-pair")).toHaveCount(0);
  await expect(reader.locator(".reader-original-title")).toHaveCount(0);
  await page.keyboard.press("v");
  await expect(rail.getByRole("radio", { name: "原文" })).toBeChecked();
  await rail.getByRole("radio", { name: "双语" }).focus();
  await page.keyboard.press("Enter");
  await expect(bilingual).toBeChecked();
  await page.setViewportSize({ width: 800, height: 800 });
  await expect(body).toHaveCSS("padding-right", "84px");
  const column = (await reader.locator(".reader-column").boundingBox())!, railBox = (await rail.boundingBox())!;
  expect(column.x + column.width).toBeLessThan(railBox.x);
});
